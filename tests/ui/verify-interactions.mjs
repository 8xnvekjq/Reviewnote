import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const output = path.resolve(process.env.UI_OUTPUT || 'node_modules/.cache/ui-renewal');
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block', reducedMotion: 'reduce' });
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  await context.routeWebSocket(/supabase/, ws => ws.close());
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5173/tests/ui/?detail');
  await page.getByRole('button', { name: '문제 이미지 확대', exact: true }).first().click();
  const zoom = page.getByRole('dialog', { name: '문제 이미지 참고창' });
  await zoom.waitFor();
  assert.equal(await page.locator('.rn-writing-window').count(), 0, 'image click must only zoom');
  await zoom.getByRole('button', { name: '문제 이미지 확대', exact: true }).click();
  await zoom.getByRole('button', { name: '문제 이미지 확대 초기화' }).click();
  await zoom.getByRole('button', { name: '문제 이미지 참고창 닫기' }).click();
  const plan = page.getByRole('textbox', { name: '나만의 대책' });
  await plan.fill('다음에는 문제 조건을 먼저 확인하고, 계산을 한 줄씩 검산할래요. '.repeat(6));
  await page.setViewportSize({ width: 390, height: 420 });
  await plan.scrollIntoViewIfNeeded();
  assert(await plan.isVisible(), 'plan available in keyboard-sized viewport');
  assert(await plan.evaluate(e => getComputedStyle(e).fontSize === '16px'), 'iOS input text size');
  await page.screenshot({ path: path.join(output, 'keyboard-sized-plan.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '풀이노트 열기' }).click();
  const first = page.locator('.rn-writing-window').first();
  const canvas = first.locator('.bg-white.relative.overflow-hidden');
  await canvas.locator('svg').waitFor();
  const box = await canvas.boundingBox();
  await page.mouse.move(box.x + 30, box.y + 60);
  await page.mouse.down();
  await page.mouse.move(box.x + 110, box.y + 110, { steps: 12 });
  await page.mouse.up();
  assert(await first.getByRole('button', { name: '직전 필기 실행 취소' }).isEnabled(), 'stroke enables undo');
  const beforePaths = await first.locator('svg path').count();
  assert(beforePaths > 0, 'stroke rendered');
  await first.getByRole('button', { name: '＋ 새 필기장', exact: true }).click();
  assert.equal(await page.locator('.rn-writing-window').count(), 2, 'two independent notebooks');
  const second = page.locator('.rn-writing-window').nth(1);
  assert(await second.getByRole('button', { name: '직전 필기 실행 취소' }).isDisabled(), 'second notebook starts blank');
  assert.equal(await first.locator('svg path').count(), beforePaths, 'first notebook stroke preserved');
  await second.getByRole('button', { name: '필기창 닫기' }).click();
  assert.equal(await first.locator('svg path').count(), beforePaths, 'closing second preserves first');
  await first.getByRole('button', { name: '직전 필기 실행 취소' }).click();
  await page.waitForFunction(() => document.querySelector('.rn-writing-window button[aria-label="직전 필기 실행 취소"]')?.disabled);
  assert.equal(await first.locator('svg path').count(), 0, 'undo removes stroke');
  await first.getByRole('button', { name: '필기창 닫기' }).click();
  await page.getByRole('button', { name: '문제 상세 닫기' }).click();
  assert(await page.locator('.rn-main').evaluate(e => !e.inert), 'background restored');
  await page.getByRole('button', { name: '럭키상점', exact: true }).click();
  await page.getByRole('button', { name: '수집 도감', exact: true }).click();
  await page.getByRole('button', { name: '오답노트', exact: true }).click();
  await page.getByRole('button', { name: '럭키상점', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '수집 도감', exact: true }).getAttribute('aria-current'), 'page', 'store subtab preserved');
  await page.getByRole('button', { name: '내 보물가방', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'inventory-empty.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '내 계정 메뉴' }).click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({ path: path.join(output, 'account-long-name.png'), animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('PASS zoom-only, keyboard-sized viewport, long text, independent notebooks, strokes/undo, store restoration, account sheet, reduced motion; 0 page errors');
} finally { await browser.close(); }
