/**
 * @param aiVoice 장착 중인 AI 말투 (없으면 기본 문구 풀 사용)
 * @param resultState 방금 체크한 복습 결과 ('O'|'X'|'star'). 빈 값이면 O 취급(기본 긍정 인사).
 */
export function getRandomCheer(aiVoice?: string, resultState?: ReviewState): string {
  const key: 'O' | 'X' | 'star' = resultState === 'X' || resultState === 'star' ? resultState : 'O';
  const pool = (aiVoice && AI_VOICE_CHEERS[aiVoice]?.[key]) || DEFAULT_CHEERS[key];
  return pool[Math.floor(Math.random() * pool.length)];
}
